-- 光和建材 営業日報・週報Webアプリ 追加スキーマ (v0.10)
-- 店舗区分を「本社」＋4営業所（いわき・仙台・福島・会津）に再編する。
-- 前提：0008_store_type.sql（stores.type列）が実行済みであること。

-- ============================================================
-- 仙台店 → 仙台営業所 に改称（スタッフの所属はそのまま維持される）
-- ============================================================

update stores set name = '仙台営業所' where name = '仙台店';

-- ============================================================
-- 新しい営業所を追加
-- ============================================================

insert into stores (name, type)
values
  ('いわき営業所', 'branch'),
  ('福島営業所', 'branch'),
  ('会津営業所', 'branch');

-- ============================================================
-- 郡山店のスタッフを本社へ移行してから、郡山店を削除する
-- ============================================================

update staff
set store_id = (select id from stores where name = '本社')
where store_id = (select id from stores where name = '郡山店');

delete from deals where store_id = (select id from stores where name = '郡山店');

delete from stores where name = '郡山店';

-- ============================================================
-- 安齋裕也（AZ01）・梨本（NM01）を会津営業所へ紐づけ
-- ============================================================

update staff
set store_id = (select id from stores where name = '会津営業所')
where staff_code in ('AZ01', 'NM01');
